/**
 * One-time: create the Ed25519 release signing key.
 *   - private key -> ~/.config/learnharness-gamification/signing-key.pem (owner-only,
 *     outside the repo; override with GAMIFICATION_PLUGIN_SIGNING_KEY)
 *   - public key  -> src/update-key.ts (built into the plugin)
 * Refuses to overwrite an existing private key: replacing it means every
 * installed copy rejects future updates until people reinstall manually.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const keyPath =
  process.env.GAMIFICATION_PLUGIN_SIGNING_KEY ??
  path.join(
    os.homedir(),
    ".config",
    "learnharness-gamification",
    "signing-key.pem",
  );
if (fs.existsSync(keyPath)) {
  console.error(
    `A signing key already exists at ${keyPath}; not overwriting it.`,
  );
  process.exit(1);
}
if (path.resolve(keyPath).startsWith(path.resolve(root) + path.sep)) {
  console.error(
    "Refusing to store the private signing key inside the repository.",
  );
  process.exit(1);
}
const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519");
fs.mkdirSync(path.dirname(keyPath), { recursive: true, mode: 0o700 });
fs.writeFileSync(keyPath, privateKey.export({ type: "pkcs8", format: "pem" }), {
  mode: 0o600,
  flag: "wx",
});
const spki = publicKey
  .export({ type: "spki", format: "der" })
  .toString("base64");
fs.writeFileSync(
  path.join(root, "src", "update-key.ts"),
  `/** Ed25519 public key (SPKI, base64) that release feeds must be signed with. Generated by scripts/keygen.mjs. */\nexport const UPDATE_PUBLIC_KEY = "${spki}";\n`,
);
console.log(
  `[keygen] private key: ${keyPath} (back this up somewhere safe; never commit it)`,
);
console.log(`[keygen] public key written to src/update-key.ts`);
